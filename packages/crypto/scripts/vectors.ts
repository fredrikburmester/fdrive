/**
 * Writes vectors/v1.json: fixed inputs and outputs of the encryption format that the Swift
 * implementation in apps/macos must reproduce. Run it only to change the format:
 * `pnpm --filter @fdrive/crypto vectors`. vectors.test.ts checks the file still holds.
 */
import { writeFile } from "node:fs/promises";
import { base64 } from "@scure/base";
import { deviceKeyFor, pairingCode } from "../src/account.ts";
import { encryptedSize, encryptStream, newKeyPair } from "../src/age.ts";
import { createFolder } from "../src/folders.ts";
import { encryptName, nameKey, nameKeyBytes } from "../src/names.ts";

function hex(bytes: Uint8Array): string {
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
}

/** The plaintext of an age vector: byte i is i mod 251. */
function pattern(length: number): Uint8Array {
  return Uint8Array.from({ length }, (_, index) => index % 251);
}

async function encrypt(bytes: Uint8Array, recipient: string): Promise<Uint8Array> {
  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      controller.enqueue(bytes);
      controller.close();
    },
  });
  return new Uint8Array(await new Response(await encryptStream(stream, recipient)).arrayBuffer());
}

const files = await newKeyPair();
const age = [];
for (const length of [0, 1, 65_536, 65_537]) {
  const ciphertext = await encrypt(pattern(length), files.recipient);
  age.push({ length, ciphertext: base64.encode(ciphertext), size: encryptedSize(length) });
}

const account = await newKeyPair();
const { marker, folder } = await createFolder(account.recipient);
const key = await nameKey(folder.identity);
const names = [];
for (const [index, name] of ["a", "Kvitton 2026.pdf", "Möte.txt", "å".repeat(64)].entries()) {
  const nonce = new Uint8Array(12).fill(index + 1);
  names.push({
    name,
    nonce: hex(nonce),
    stored: await encryptName(name, key, folder.id, nonce),
  });
}

const device = await newKeyPair();
const vectors = {
  description:
    "Encrypted folder format v1. See docs/ENCRYPTION.md. Generated by packages/crypto/scripts/vectors.ts.",
  age: {
    identity: files.identity,
    recipient: files.recipient,
    plaintext: "byte i = i % 251",
    files: age,
  },
  folder: {
    accountIdentity: account.identity,
    marker,
    identity: folder.identity,
    nameKey: hex(await nameKeyBytes(folder.identity)),
    names,
  },
  device: {
    identity: device.identity,
    recipient: device.recipient,
    pairingCode: await pairingCode(device.recipient),
    accountRecipient: account.recipient,
    deviceKey: await deviceKeyFor(account.identity, device.recipient),
  },
};

await writeFile(
  new URL("../vectors/v1.json", import.meta.url),
  `${JSON.stringify(vectors, null, 2)}\n`,
);
